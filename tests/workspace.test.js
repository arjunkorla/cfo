// derived values are recomputed here, and the documented severity / priority / status rules are re-applied.
test('overview data: figures trace to CFO_SAMPLE; derived values and rules recomputed', async () => {
  const OV = JSON.parse(JSON.stringify(vm.runInNewContext(fs.readFileSync(path.join(ROOT, 'components', 'cfo-overview-data.js'), 'utf8') + '\n;CFO_OVERVIEW;', {}), (k, v) => typeof v === 'function' ? undefined : v));
  const ovFns = vm.runInNewContext(fs.readFileSync(path.join(ROOT, 'components', 'cfo-overview-data.js'), 'utf8') + '\n;CFO_OVERVIEW;', {});
  const cache = {};
  const agentOf = {}; for (const c of CATS) for (const a of S.listAgents(c)) agentOf[a.id] = c;
  async function sum(c, a) { assert.equal(agentOf[a], c, `${a} belongs to ${c}`); return cache[a] || (cache[a] = await S.getSummary(REQ(c, a))); }
  async function text(c, a) { return JSON.stringify(await sum(c, a)).replace(/\\u2013/g, '–'); }
  async function has(c, a, s, what) { assert.ok((await text(c, a)).includes(JSON.stringify(s).slice(1, -1)), `${what}: "${s}" not found in ${c}/${a}`); }
  const pct = (a, b) => Math.round(a / b * 100);

  // KPI snapshot
  assert.deepEqual(OV.kpis.map(k => k.id), ['total-ar', 'overdue-ar', 'cash-received', 'dso', 'unapplied', 'disputes']);
  for (const k of OV.kpis) {
    await has(k.src[0], k.src[1], k.display, 'KPI ' + k.id);
    for (const f of k.find) await has(k.src[0], k.src[1], f, 'KPI ' + k.id);
    for (const [c, a, f] of k.also || []) await has(c, a, f, 'KPI ' + k.id);
    if (k.series) {
      const chart = (await sum(k.src[0], k.src[1])).chart;
      assert.deepEqual(k.series, chart.values, `${k.id} series = ${k.src[1]} chart`);
      assert.equal(k.compare.prior, k.series[3], `${k.id}: prior month is the 4th value of the series`);
      assert.equal(k.value, k.series[4], `${k.id}: current value is the last value of the series`);
    }
  }
  const K = Object.fromEntries(OV.kpis.map(k => [k.id, k]));
  assert.equal(pct(2.4, 8.6), 28); assert.match(K['overdue-ar'].sub, /^28% of total AR$/);
  assert.equal((2.40 - 2.28).toFixed(2), '0.12'); assert.equal(((2.40 - 2.28) / 2.28 * 100).toFixed(1), '5.3');
  assert.equal(K['overdue-ar'].compare.delta, '+$0.12M (+5.3%)'); assert.equal(K['overdue-ar'].target.note, '$0.4M above sample target');
  assert.equal(K.dso.compare.delta, '+1 day'); assert.equal(K.dso.target.note, '3 days above sample target');
  assert.equal(pct(4.7, 5.2), 90); assert.equal(pct(0.5, 5.2), 10); assert.equal(pct(6.20, 8.6), 72);
  for (const k of OV.kpis) if (!k.series) assert.equal(k.compare, null, `${k.id}: no prior period exists in the sample, so none is shown`);

  // Alerts: sources, documented severity rule, ordering, existing routes
  const trend = async (c, a) => (await sum(c, a)).chart.values;
  const rising = v => v.every((x, i) => i === 0 || x > v[i - 1]);
  for (const al of OV.alerts) {
    for (const f of al.find) await has(al.src[0], al.src[1], f, 'alert ' + al.id);
    const m = /^cfo-workspace\.html\?category=([a-z-]+)&agent=([a-z0-9-]+)$/.exec(al.href);
    assert.ok(m && agentOf[m[2]] === m[1] && al.categories.includes(m[1]), 'alert link uses an existing category + agent: ' + al.href);
    const expect = al.severity === 'critical' ? 'critical' : al.stake >= 0.5 ? 'high' : al.stake > 0 ? 'medium' : 'info';
    assert.equal(al.severity, expect, 'severity rule: ' + al.id);
  }
  const crit = OV.alerts.filter(a => a.severity === 'critical');
  assert.deepEqual(crit.map(a => a.id), ['overdue-dso']);
  const ov = await trend('kpis', 'kpi-overdue'), dso = await trend('receivables', 'ar-dso');
  assert.ok(rising(ov) && ov[4] > 2.0 && rising(dso) && dso[4] > 45, 'critical = off sample target and worse in every month');
  await has('kpis', 'kpi-scorecard', '48 vs 45 days', 'DSO target'); await has('kpis', 'kpi-overdue', '$2.4M vs $2.0M', 'overdue target');
  const order = JSON.parse(JSON.stringify(ovFns.sortedAlerts().map(a => a.id)));
  assert.deepEqual(order, ['overdue-dso', 'high-risk-credit', 'priority-disputes', 'unapplied-cash', 'bad-debt', 'broken-promises', 'invoice-holds', 'cei-gap']);
  assert.equal(ovFns.sortedAlerts([]).length, 0, 'empty alert list supported');

  // Category cards: same 8 ids in order; metrics/counts from the category's own agents
  assert.deepEqual(OV.categories.map(c => c.id), CATS);
  for (const c of OV.categories) {
    for (const [label, display, agent, find] of c.metrics) {
      await has(c.id, agent, find, `${c.id} metric ${label}`);
      for (const part of display.split(' / ')) if (!/^[+]/.test(part)) await has(c.id, agent, part, `${c.id} metric ${label}`);
    }
    if (c.count) await has(c.id, c.count[2], c.count[3], `${c.id} count`);
  }
  assert.equal(pct(0.62, 1.15), 54);
  await has('efficiency', 'bm-dso', 'DSO is 6 days above the peer median', '+6 days');
  const sc = (await sum('kpis', 'kpi-scorecard')).chart.values; assert.ok(sc.length === 5 && sc.every(v => v < 100), '5 of 5 KPIs below sample target');
  await has('kpis', 'kpi-cashapp', 'Gap to the 93% target', 'cash application target');
  const status = Object.fromEntries(CATS.map(c => [c, ovFns.categoryStatus(c).label]));
  assert.deepEqual(status, { credit: 'Needs attention', collections: 'Needs attention', receivables: 'Needs attention', 'cash-app': 'Needs attention', disputes: 'Needs attention', 'portal-usage': 'No major alerts', efficiency: 'No major alerts', kpis: 'Needs attention' });

  // Action tracker: sample recommendations verbatim; priority rule; honest status
  for (const a of OV.actions) {
    await has(a.category, a.agent, a.find, 'action ' + a.id);
    assert.equal(a.action, a.find, 'action wording unchanged: ' + a.id);
    assert.equal(a.priority, a.stake >= 0.5 ? 'high' : 'medium', 'priority rule: ' + a.id);
  }
  // Briefing: every item cites its agent; no AI claims
  const B = OV.briefing;
  for (const it of [...B.positives, ...B.risks, ...B.actions]) await has(it.c, it.a, it.find, 'briefing: ' + it.text);
  assert.deepEqual([...new Set([...B.positives, ...B.risks, ...B.actions].map(i => i.kind))].sort(), ['Fact', 'Recommendation', 'Trend']);
  const all = JSON.stringify(OV);
  assert.ok(!/\b(AI[- ]generated|generated by|real[- ]time|live data|LLM)\b/i.test(all), 'no AI-generation or live-data claims in the overview data');
});

