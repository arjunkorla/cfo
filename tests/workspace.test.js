function loadSample() {
  assert.ok(sampleSrc.includes('var CFO_SAMPLE=(function(){'), 'CFO_SAMPLE not found in components/cfo-sample-data.js');
  for (const p of ['cfo-workspace.html', 'cfo-overview.html'])
    assert.ok(fs.readFileSync(path.join(ROOT, p), 'utf8').includes('<script src="components/cfo-sample-data.js"></script>'), p + ' must load the sample data layer');
  const raw = vm.runInNewContext(sampleSrc + '\n;CFO_SAMPLE;', { setTimeout, Promise });
  // Results are created inside the VM; copy them to this realm so deepEqual compares values, not prototypes.
  const plain = v => JSON.parse(JSON.stringify(v));
  return {
    listCategories: () => plain(raw.listCategories()),
    listAgents: c => plain(raw.listAgents(c)),
    getSummary: r => raw.getSummary(r).then(plain),
    answer: r => raw.answer(r).then(plain),
    format: raw.format
  };
}
const S = loadSample();
const CATS = ['credit', 'collections', 'receivables', 'cash-app', 'disputes', 'portal-usage', 'efficiency', 'kpis'];
const REQ = (categoryId, agentId) => ({ categoryId, agentId, from: '2026-10-14', to: '2026-11-12', provider: 'p', model: 'm', prompt: 'x' });
const sum = a => Math.round(a.reduce((x, y) => x + y, 0) * 100) / 100;
const PLACEHOLDER = /\[|Data source not connected|Response placeholder|generated by the model/;

