test('getSummary: contract for all 32 agents, deterministic, distinct charts', async () => {
  const titles = new Set();
  for (const c of CATS) for (const a of S.listAgents(c)) {
    const r = await S.getSummary(REQ(c, a.id));
    assert.equal(r.origin, 'sample');
    assert.deepEqual(r.sections.map(s => s.key + ':' + s.items.length), ['insights:3', 'risks:2', 'recommendations:2'], a.id);
    for (const s of r.sections) for (const it of s.items) {
      for (const k of ['title', 'metric', 'value', 'impact']) assert.ok(it[k] && !PLACEHOLDER.test(it[k]), `${a.id} ${k}`);
      assert.ok(it.source.id && it.source.report, `${a.id} source`);
    }
    assert.ok(['usdM', 'usdK', 'pct', 'days', 'count'].includes(r.chart.unit), a.id);
    assert.equal(r.chart.labels.length, r.chart.values.length, a.id);
    assert.ok(r.chart.values.every(Number.isFinite) && r.chart.values.length >= 3, a.id);
    titles.add(r.chart.title);
    assert.deepEqual(await S.getSummary(REQ(c, a.id)), r, 'deterministic ' + a.id);
  }
  assert.equal(titles.size, 32);
  await assert.rejects(S.getSummary(REQ('credit', 'unknown')));
});

