/* ---------------- browser regression (headless Chrome / Edge) ---------------- */
function findChrome() {
  const c = [process.env.CHROME_PATH, 'C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',
    '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', '/usr/bin/google-chrome', '/usr/bin/chromium', '/usr/bin/chromium-browser'];
  return c.find(p => p && fs.existsSync(p)) || null;
}
const CHROME = findChrome();
const TMP = CHROME ? fs.mkdtempSync(path.join(os.tmpdir(), 'cfo-ws-')) : null;

// The temp copy keeps the page's real file name (sidebar active-item detection uses it) and gets a <base> pointing at
// the project root so the shared components/ files resolve.
const BASE = '<base href="file:///' + ROOT.replace(/\\/g, '/').replace(/\/?$/, '/') + '">';
function runHarness(harnessFile, width, budget, pageFile = 'cfo-workspace.html') {
  const j = fs.readFileSync(path.join(__dirname, 'harness', harnessFile), 'utf8');
  const src = pageFile === 'cfo-workspace.html' ? html : fs.readFileSync(path.join(ROOT, pageFile), 'utf8');
  const withBase = src.replace(/<head>/i, m => m + BASE);
  assert.ok(withBase !== src, 'no <head> in ' + pageFile);
  const i = withBase.lastIndexOf('</body>');
  const dir = fs.mkdtempSync(path.join(TMP, `${path.basename(harnessFile, '.js')}-${width}-`));
  const file = path.join(dir, pageFile);
  fs.writeFileSync(file, withBase.slice(0, i) + '<script>' + j + '</script>' + withBase.slice(i));
  // Headless Chrome won't size a window below ~500px, so phone widths run the page in an iframe of exactly `width`
  // (844px high); the wrapper copies the harness output out of the iframe.
  let target = file, win = width;
  if (width < 600) {
    target = path.join(dir, 'viewport-wrapper.html'); win = 800;
    fs.writeFileSync(target, '<!doctype html><html><body style="margin:0"><iframe id="f" src="' + pageFile + '" style="border:0;width:' + width + 'px;height:844px"></iframe>' +
      '<script>var t=setInterval(function(){try{var o=document.getElementById("f").contentDocument.getElementById("harnessOut");' +
      'if(o){clearInterval(t);var p=document.createElement("pre");p.id="harnessOut";p.textContent=o.textContent;document.body.appendChild(p)}}catch(e){}},200)</script></body></html>');
  }
  // --allow-file-access-from-files: same-folder iframes (viewport wrapper, cross-page language check) can be read
  const out = spawnSync(CHROME, ['--headless=new', '--disable-gpu', '--no-first-run', '--allow-file-access-from-files', `--user-data-dir=${path.join(dir, 'profile')}`,
    `--virtual-time-budget=${budget}`, `--window-size=${win},1000`, '--dump-dom', 'file:///' + target.replace(/\\/g, '/')],
    { encoding: 'utf8', timeout: 280000, maxBuffer: 64 * 1024 * 1024 });
  const m = /<pre id="harnessOut">([\s\S]*?)<\/pre>/.exec(out.stdout || '');
  assert.ok(m, 'harness produced no output (browser failed to run?) ' + (out.error ? out.error.message : ''));
  return JSON.parse(m[1].replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&amp;/g, '&'));
}
function assertAll(results, minCount) {
  assert.ok(results.length >= minCount, `expected ≥${minCount} checks, got ${results.length}`);
  const failed = results.filter(r => !r.pass);
  assert.equal(failed.length, 0, failed.map(f => `${f.name} :: ${f.info}`).join('\n'));
}
const SKIP = CHROME ? false : 'No Chrome/Edge found (set CHROME_PATH) — browser regression skipped';

test('browser: all 32 agents, chat, charts, exports, actions, keyboard (1600px)', { skip: SKIP, timeout: 300000 }, () => {
  assertAll(runHarness('workspace.harness.js', 1600, 400000), 350);
});
for (const w of [1024, 768, 390]) {
  test(`browser: responsive layout at ${w}px`, { skip: SKIP, timeout: 120000 }, () => {
    assertAll(runHarness('narrow.harness.js', w, 20000), 6);
  });
}

